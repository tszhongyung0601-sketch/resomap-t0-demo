export const BY_STORY: Record<string, Story> = Object.fromEntries(
  STORIES.map((s) => [s.id, s]),
);

export const story = (id: string | undefined): Story | undefined =>
  id ? BY_STORY[id] : undefined;

/**
 * A story belongs to a place, and a place belongs to a destination — the story
 * itself never carries a `destId`, because a POI moving city should not require
 * editing its guide. The POI arrays are imported directly rather than through
 * `./index`, which re-exports this file and would close a cycle.
 */
const DEST_OF_POI: Record<string, string> = Object.fromEntries(
  [...POI_TW_NORTH, ...POI_TW_SOUTH, ...POI_TW_EAST, ...POI_OVERSEAS].map(
    (p) => [p.id, p.destId],
  ),
);

export const storiesForDest = (destId: string): Story[] =>
  STORIES.filter((s) => DEST_OF_POI[s.poiId] === destId);
